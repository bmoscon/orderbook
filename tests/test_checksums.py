def test_bitfinex_checksum_overflow():
    for length in range(4000, 4200):
        ob = OrderBook(checksum_format='BITFINEX')
        ob.bids = {Decimal(1): Decimal(1)}
        ob.asks = {Decimal('1' * length): Decimal(1)}

        try:
            assert isinstance(ob.checksum(), int)
        except ValueError:
            pass


