def l3_book(bids, asks, reverse=False):
    ob = OrderBook(checksum_format='BITFINEX')

    for side, orders in ((ob.bids, bids), (ob.asks, asks)):
        for order_id, price, amount in (reversed(orders) if reverse else orders):
            price = Decimal(price)

            if price in side:
                side[price][order_id] = Decimal(amount)
            else:
                side[price] = {order_id: Decimal(amount)}

    return ob


